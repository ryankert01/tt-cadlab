#!/usr/bin/env python3
"""Summarise the group-mode cap sweep (docs/results/raw/bench_*_g8_*.json) into a markdown table.
Usage: python scripts/sweep_group_cap_summary.py            -> writes docs/results/stage2g_group_cap.md
       python scripts/sweep_group_cap_summary.py --best TAG B -> prints "hHcC" of the best cap-8 layout at
                                                                 4k for that dump/batch if it beats H=1, else nothing
"""
import json, re, sys
from pathlib import Path
RAW = Path("docs/results/raw")
PAT = re.compile(r"bench_(attention|decode)_g8_(glrd\d+)_h(\d)c(\d)(?:_b(\d+))?\.json")

def load():
    cells = {}
    for p in RAW.glob("bench_*_g8_*.json"):
        m = PAT.match(p.name)
        if not m: continue
        what, tag, h, cap, b = m.group(1), m.group(2), int(m.group(3)), int(m.group(4)), int(m.group(5) or 32)
        d = json.loads(p.read_text())
        cells[(what, tag, b, h, cap)] = d
    return cells

def cell_ms(d, ctx, key="min_ms"):
    r = d["data"].get(str(ctx)) or d["data"].get(ctx)
    if not r or key not in r: return None
    return r[key]

def main():
    cells = load()
    if len(sys.argv) >= 4 and sys.argv[1] == "--best":
        tag, b = sys.argv[2], int(sys.argv[3])
        base = next((d for (w, t, bb, h, c), d in cells.items() if w == "attention" and t == tag and bb == b and h == 1), None)
        base_ms = cell_ms(base, 4096) if base else None
        best, best_ms = None, None
        for (w, t, bb, h, c), d in cells.items():
            if w != "attention" or t != tag or bb != b or c != 8: continue
            ms = cell_ms(d, 4096)
            if ms is not None and (best_ms is None or ms < best_ms): best, best_ms = (h, c), ms
        if best and base_ms and best_ms < base_ms * 0.99: print(f"h{best[0]}c{best[1]}")
        return
    out = ["# Group-mode cap sweep (stage 2g draft)", "",
           "Attention-only decode of layer 0, `--fused p2`, shipped rotation switches, 20 timed iterations; `min / p50` ms; "
           "`x` = ratio of the cell's min to the per-head (H = 1) min at the same batch and context; "
           "`!` marks p50/min > 1.03 (a contaminated wall clock). Generated by `scripts/sweep_group_cap_summary.py`.", ""]
    for what in ("attention", "decode"):
        for tag in ("glrd50", "glrd70"):
            rows = sorted({(b, h, c) for (w, t, b, h, c) in cells if w == what and t == tag}, key=lambda x: (x[0], x[1], x[2]))
            if not rows: continue
            out += [f"## {what}: `{tag}`", "", "| batch | H | cap | active cores / rounds | 1k | 4k | 8k |", "|---|---|---|---|---|---|---|"]
            for b, h, c in rows:
                d = cells[(what, tag, b, h, c)]
                base = cells.get((what, tag, b, 1, 4))
                layout = d.get("group_heads_per_layer")
                vals = []
                for ctx in (1024, 4096, 8192):
                    r = d["data"].get(str(ctx)) or {}
                    if "min_ms" not in r:
                        vals.append("ERR: " + str(r.get("error", "?"))[:40]); continue
                    flag = "!" if r["p50_ms"] > 1.03 * r["min_ms"] else ""
                    s = f"{r['min_ms']:.2f} / {r['p50_ms']:.2f}{flag}"
                    bm = cell_ms(base, ctx) if base else None
                    if bm and h != 1: s += f" (x{r['min_ms'] / bm:.3f})"
                    vals.append(s)
                out.append(f"| {b} | {h} | {c} | {layout} | " + " | ".join(vals) + " |")
            out.append("")
    # device profiles: per-step device time of the attention op and of the whole step, per cell
    PPAT = re.compile(r"profile_g8_(glrd\d+)_h(\d)c(\d)_b(\d+)_(\d+)\.json")
    prof = {}
    for q in RAW.glob("profile_g8_*.json"):
        m = PPAT.match(q.name)
        if m:
            tag, h, c, b, ctx = m.group(1), int(m.group(2)), int(m.group(3)), int(m.group(4)), int(m.group(5))
            prof[(tag, ctx, b, h, c)] = json.loads(q.read_text())
    if prof:
        out += ["## Device profiles (tracy): per decode step, 32 layers, chip 0", "",
                "`attention` = device ms of the fused attention op per step; `step` = all ops; `x` = ratio to H = 1 at the same batch and context. "
                "Immune to host noise; this is the number that decides the cap.", "",
                "| dump | ctx | batch | H | cap | attention ms | x | step ms | x |", "|---|---|---|---|---|---|---|---|---|"]
        for (tag, ctx, b, h, c) in sorted(prof):
            d = prof[(tag, ctx, b, h, c)]; base = prof.get((tag, ctx, b, 1, 4))
            att = d["categories"].get("attention", {}).get("ms"); step = d["device_ms_per_step"]
            batt = base["categories"].get("attention", {}).get("ms") if base else None
            bstep = base["device_ms_per_step"] if base else None
            xa = f"{att / batt:.3f}" if (att and batt and h != 1) else ""
            xs = f"{step / bstep:.3f}" if (step and bstep and h != 1) else ""
            out.append(f"| {tag} | {ctx} | {b} | {h} | {c} | {att:.3f} | {xa} | {step:.2f} | {xs} |")
        out.append("")
    Path("docs/results/stage2g_group_cap.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))

if __name__ == "__main__":
    main()
